// Writes docs/scene-shapes.md: the shape of every scene, taken from real scenes built
// from small samples, so the reference never drifts from the code.
// Run: node --import ./scripts/jsx-register.mjs scripts/scene-doc.mjs
import { writeFileSync } from 'node:fs'
import * as C from '../src/core.js'

const pts = pairs => pairs.map(([x, y]) => ({ x, y, type: 'actual' }))
const res = (label, pairs, extra = {}) => ({ label, unit: 'M', nature: 'flow', role: 'actual', points: pts(pairs), ...extra })
const S = (id, mark, extra = {}) => ({ id, ref: { metric: 'sales', source: 'actual' }, mark, ...extra })
const resolved = [res('North', [['2022', 40], ['2023', 52], ['2024', 61]]), res('Plan', [['2022', 60], ['2023', 75], ['2024', 95]], { role: 'plan' })]
const cspec = C.withDefaults({ id: 'doc', version: 1, kind: 'cartesian', x: { grain: 'year', range: 'all' }, series: [S('north', 'bar', { labels: 'all' }), S('plan', 'line')], annotations: [{ type: 'cagr', series: 'north' }] }, resolved)
const bridge = { unit: 'M', steps: [{ key: 's', label: 'Entry', kind: 'anchor', value: 200, tone: 'anchor' }, { key: 'g', label: 'Growth', kind: 'delta', value: 40, tone: 'positive' }, { key: 'd', label: 'Debt', kind: 'delta', value: -26, tone: 'negative' }, { key: 'e', label: 'Exit', kind: 'total', value: 0, tone: 'anchor' }] }

const SAMPLES = {
  chart: () => C.buildScene(cspec, resolved, { width: 720, height: 360 }),
  waterfall: () => C.buildWaterfallScene({ annotations: [{ type: 'diff', from: 's', to: 'e' }] }, bridge, { width: 720, height: 360 }),
  barh: () => C.buildBarhScene({ series: [{ id: 'v', label: 'Value', color: 'cat-1' }], rangeMarker: 'median', rangeMarkerLabel: true }, [{ key: 'a', label: 'Comps', values: { v: 40 }, range: [80, 130], points: [80, 102, 130] }, { key: 'b', label: 'DCF', values: { v: 35 }, range: [90, 140], points: [90, 118, 140] }], { width: 600 }),
  pie: () => C.buildPieScene({ donut: 0.55, total: true }, [{ key: 'a', label: 'North', value: 40 }, { key: 'b', label: 'South', value: 35 }], { width: 600, height: 300 }),
  scatter: () => C.buildScatterScene({ bubble: true, trend: true }, [{ key: 'a', label: 'Alpha', x: 1.5, y: 2.1, size: 10, group: 'N' }, { key: 'b', label: 'Beta', x: 2.5, y: 4.3, size: 40, group: 'S' }, { key: 'c', label: 'Gamma', x: 3.5, y: 5.8, size: 90, group: 'S' }], { width: 600, height: 360 }),
  mekko: () => C.buildMekkoScene({ series: [{ id: 'x', label: 'Leader' }, { id: 'y', label: 'Challenger' }] }, [{ key: 'eu', label: 'Europe', values: { x: 50, y: 30 } }, { key: 'us', label: 'Americas', values: { x: 40, y: 40 } }], { width: 600, height: 320 }),
  gantt: () => C.buildGanttScene({}, [{ key: 'd', label: 'Design', items: [{ key: 'd1', start: '2025-01-06', end: '2025-02-14', label: 'Mockups', done: 0.5 }] }, { key: 'l', label: 'Launch', items: [{ key: 'm1', start: '2025-03-05', kind: 'milestone', label: 'Go live' }] }], { width: 720 }),
  table: () => C.buildTableScene({}, [{ key: 'rev', label: 'Revenue', type: 'number' }, { key: 'fit', label: 'Fit', type: 'harvey' }], [{ key: 'a', label: 'North', cells: { rev: 1234.5, fit: 0.75 } }], { width: 600 }),
  slope: () => C.buildSlopeScene({ before: '2019', after: '2024', change: true }, [{ key: 'a', label: 'Alpha', before: 12, after: 18 }, { key: 'b', label: 'Beta', before: 20, after: 9 }], { width: 600, height: 320 }),
  funnel: () => C.buildFunnelScene({ rates: true }, [{ key: 'a', label: 'Universe', value: 1250 }, { key: 'b', label: 'Targets', value: 180, filter: 'EBITDA > 5' }, { key: 'c', label: 'Finalists', value: 3 }], { width: 600, height: 300 }),
}

const kind = v => (v === null ? 'null' : Array.isArray(v) ? 'array' : typeof v)
// One line per path; arrays are described by the union of their elements' keys.
function shape(v, path, out, depth = 0) {
  if (depth > 4) return
  const k = kind(v)
  if (k === 'array') {
    out.push([path, `array (${v.length} in the sample)`])
    const merged = {}
    for (const it of v) if (kind(it) === 'object') for (const [kk, vv] of Object.entries(it)) if (!(kk in merged) || merged[kk] == null) merged[kk] = vv
    if (Object.keys(merged).length) for (const [kk, vv] of Object.entries(merged)) shape(vv, `${path}[].${kk}`, out, depth + 1)
    else if (v.length) out.push([`${path}[]`, kind(v[0])])
    return
  }
  if (k === 'object') {
    if (path) out.push([path, 'object'])
    for (const [kk, vv] of Object.entries(v)) shape(vv, path ? `${path}.${kk}` : kk, out, depth + 1)
    return
  }
  const ex = k === 'string' ? JSON.stringify(v.length > 40 ? `${v.slice(0, 37)}…` : v) : k === 'number' ? String(Math.round(v * 100) / 100) : String(v)
  out.push([path, `${k} · e.g. ${ex}`])
}

let md = `# Scene shapes

Generated by \`scripts/scene-doc.mjs\` from real scenes (small samples): do not edit by hand.
Read [scenes.md](scenes.md) first for the conventions (pixels, colors, text, meta).

`
for (const [name, build] of Object.entries(SAMPLES)) {
  const out = []
  shape(build(), '', out)
  md += `## ${name}\n\n| Path | Type |\n|---|---|\n${out.filter(([p]) => !p.startsWith('meta.')).map(([p, t]) => `| \`${p}\` | ${t.replace(/\|/g, '\\|')} |`).join('\n')}\n\n`
}
writeFileSync(new URL('../docs/scene-shapes.md', import.meta.url), md)
console.log('docs/scene-shapes.md written')
